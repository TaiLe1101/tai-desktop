import type { CaptionTrackInfo } from './types';

export const YOUTUBE_LANGUAGE_ALIASES: Record<string, string[]> = {
  'zh-CN': ['zh-Hans', 'zh-CN', 'zh-SG'],
  'zh-TW': ['zh-Hant', 'zh-TW'],
  'zh-HK': ['yue', 'yue-HK', 'zh-HK'],
  he: ['iw', 'he'],
  no: ['no', 'nb']
};

function normalizeTag(code: string): string {
  return (code || '').trim().replace(/_/g, '-').toLowerCase();
}

/**
 * Finds the best matching YouTube language code for a target language.
 * Uses explicit alias tables for zh-CN/zh-TW/zh-HK/he/no and forbids fuzzy
 * base-language matching for "zh" (to prevent mixing Simplified/Traditional/Cantonese).
 */
export function findYouTubeLanguage(targetLang: string, availableCodes: string[]): string | null {
  if (!targetLang || !availableCodes.length) return null;
  const targetNorm = normalizeTag(targetLang);
  const normalizedMap = new Map<string, string>();
  for (const code of availableCodes) {
    const norm = normalizeTag(code);
    if (norm && !normalizedMap.has(norm)) normalizedMap.set(norm, code);
  }

  // 1. Exact case-insensitive match
  const exact = normalizedMap.get(targetNorm);
  if (exact) return exact;

  // 2. Explicit alias list lookup
  const aliasKey = Object.keys(YOUTUBE_LANGUAGE_ALIASES).find(k => normalizeTag(k) === targetNorm);
  if (aliasKey) {
    for (const alias of YOUTUBE_LANGUAGE_ALIASES[aliasKey]) {
      const hit = normalizedMap.get(normalizeTag(alias));
      if (hit) return hit;
    }
    return null;
  }

  // 3. Base language match, explicitly forbidding fuzzy "zh"
  const base = targetNorm.split('-')[0];
  if (!base || base === 'zh') return null;

  if (normalizedMap.has(base)) return normalizedMap.get(base)!;
  for (const [norm, original] of normalizedMap.entries()) {
    if (norm.split('-')[0] === base) return original;
  }
  return null;
}

/**
 * Normalizes a BCP-47 language tag to its spoken language family.
 * Separates Cantonese ("yue") from Mandarin ("zh-mandarin").
 */
export function normalizeSpokenLanguage(code: string | undefined | null): string {
  const norm = normalizeTag(code || '');
  if (!norm) return '';
  if (norm === 'yue' || norm.startsWith('yue-') || norm.startsWith('zh-yue') || norm === 'zh-hk' || norm.startsWith('zh-hk-')) {
    return 'yue';
  }
  if (norm === 'zh' || norm.startsWith('zh-') || norm === 'cmn' || norm.startsWith('cmn-')) {
    return 'zh-mandarin';
  }
  if (norm === 'iw' || norm.startsWith('iw-') || norm === 'he' || norm.startsWith('he-')) {
    return 'he';
  }
  if (norm === 'nb' || norm.startsWith('nb-') || norm === 'nn' || norm.startsWith('nn-') || norm === 'no' || norm.startsWith('no-')) {
    return 'no';
  }
  return norm.split('-')[0];
}

export function isSameSpokenLanguage(langA: string | undefined | null, langB: string | undefined | null): boolean {
  const a = normalizeSpokenLanguage(langA);
  const b = normalizeSpokenLanguage(langB);
  return Boolean(a && b && a === b);
}

/**
 * Selects the highest-quality source caption track matching the video's spoken language:
 * 1. Manual track matching ASR exact languageCode
 * 2. Manual track matching ASR spoken/base language (no fuzzy zh confusion)
 * 3. ASR track matching originalAudioLanguage (or sole ASR track)
 * 4. Manual track matching originalAudioLanguage (or sole manual language)
 * 5. Fallback to first available track.
 */
export function selectSourceTrack(
  tracks: CaptionTrackInfo[],
  originalAudioLanguage?: string
): CaptionTrackInfo | null {
  if (!tracks.length) return null;

  const manual = tracks.filter(t => !t.isAutoGenerated);
  const asr = tracks.filter(t => t.isAutoGenerated);

  const primaryAsr = (originalAudioLanguage
    ? asr.find(t => isSameSpokenLanguage(t.languageCode, originalAudioLanguage))
    : undefined)
    || (asr.length === 1 ? asr[0] : asr[0]);

  if (primaryAsr) {
    const asrCode = normalizeTag(primaryAsr.languageCode);
    const exactManual = manual.find(t => normalizeTag(t.languageCode) === asrCode);
    if (exactManual) return exactManual;

    const baseManual = manual.find(t => {
      const mNorm = normalizeTag(t.languageCode);
      const mBase = mNorm.split('-')[0];
      const aBase = asrCode.split('-')[0];
      if (mBase === 'zh' || aBase === 'zh') {
        return isSameSpokenLanguage(t.languageCode, primaryAsr.languageCode);
      }
      return mBase === aBase;
    });
    if (baseManual) return baseManual;

    if (originalAudioLanguage && isSameSpokenLanguage(primaryAsr.languageCode, originalAudioLanguage)) {
      return primaryAsr;
    }
    if (asr.length === 1) return primaryAsr;
  }

  if (originalAudioLanguage) {
    const origManual = manual.find(t => isSameSpokenLanguage(t.languageCode, originalAudioLanguage));
    if (origManual) return origManual;
    const origAsr = asr.find(t => isSameSpokenLanguage(t.languageCode, originalAudioLanguage));
    if (origAsr) return origAsr;
  }

  const manualBaseLangs = new Set(manual.map(t => normalizeSpokenLanguage(t.languageCode)).filter(Boolean));
  if (manualBaseLangs.size === 1 && manual.length > 0) {
    return manual[0];
  }

  return primaryAsr || manual[0] || tracks[0];
}

/**
 * Rewrites a YouTube /api/timedtext URL to force fmt=json3 while preserving
 * authorization/signature parameters (pot, expire, sig, etc.).
 */
export function buildSourceTimedtextUrl(baseUrl: string, tlang?: string | null): string {
  const url = new URL(baseUrl);
  url.searchParams.set('fmt', 'json3');
  if (tlang === null) {
    url.searchParams.delete('tlang');
  } else if (typeof tlang === 'string' && tlang.trim()) {
    url.searchParams.set('tlang', tlang.trim());
  }
  return url.toString();
}

export function hasTimedtextPot(urlStr: string): boolean {
  try {
    const url = new URL(urlStr);
    const pot = url.searchParams.get('pot');
    return Boolean(pot && pot.trim().length > 0);
  } catch {
    return false;
  }
}

export const TIMEDTEXT_EXPIRY_BUFFER_MS = 60_000;

export function isTimedtextUrlUsable(urlStr: string, videoId: string, nowMs = Date.now()): boolean {
  try {
    const url = new URL(urlStr);
    if (url.protocol !== 'https:') return false;
    if (!(url.hostname === 'youtube.com' || url.hostname.endsWith('.youtube.com'))) return false;
    if (url.pathname !== '/api/timedtext') return false;
    if (url.searchParams.get('v') !== videoId) return false;
    const expireRaw = url.searchParams.get('expire');
    if (expireRaw) {
      const expireSec = Number(expireRaw);
      if (Number.isFinite(expireSec) && expireSec * 1000 <= nowMs + TIMEDTEXT_EXPIRY_BUFFER_MS) {
        return false;
      }
    }
    return true;
  } catch {
    return false;
  }
}
