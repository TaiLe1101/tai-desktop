import { describe, it } from 'node:test';
import assert from 'node:assert/strict';
import {
  buildSourceTimedtextUrl,
  findYouTubeLanguage,
  hasTimedtextPot,
  isSameSpokenLanguage,
  isTimedtextUrlUsable,
  selectSourceTrack
} from '../src/shared/languages';
import {
  TARGET_LANGUAGES,
  computeEffectiveSpeechRate,
  formatSsmlRate,
  getDefaultVoice,
  resolveLanguageEntry
} from '../src/shared/voices';
import type { CaptionTrackInfo } from '../src/shared/types';

describe('findYouTubeLanguage & aliases', () => {
  it('resolves zh-CN, zh-TW, zh-HK, he, no via explicit alias tables', () => {
    assert.equal(findYouTubeLanguage('zh-CN', ['en', 'zh-Hans', 'zh-Hant']), 'zh-Hans');
    assert.equal(findYouTubeLanguage('zh-TW', ['en', 'zh-Hant']), 'zh-Hant');
    assert.equal(findYouTubeLanguage('zh-HK', ['en', 'yue', 'zh-Hans']), 'yue');
    assert.equal(findYouTubeLanguage('he', ['en', 'iw']), 'iw');
    assert.equal(findYouTubeLanguage('no', ['en', 'nb']), 'nb');
  });

  it('forbids fuzzy zh fallback across Simplified/Traditional/Cantonese', () => {
    assert.equal(findYouTubeLanguage('zh-TW', ['zh-Hans', 'en']), null);
    assert.equal(findYouTubeLanguage('zh-HK', ['zh-CN', 'zh-Hant']), null);
    assert.equal(findYouTubeLanguage('zh', ['zh-Hans']), null);
  });
});

describe('isSameSpokenLanguage', () => {
  it('separates Cantonese from Mandarin and matches spoken families', () => {
    assert.equal(isSameSpokenLanguage('zh-CN', 'zh-Hans'), true);
    assert.equal(isSameSpokenLanguage('zh-CN', 'zh-TW'), true);
    assert.equal(isSameSpokenLanguage('zh-HK', 'yue'), true);
    assert.equal(isSameSpokenLanguage('zh-HK', 'zh-CN'), false);
    assert.equal(isSameSpokenLanguage('yue-HK', 'zh-Hans'), false);
    assert.equal(isSameSpokenLanguage('he', 'iw'), true);
    assert.equal(isSameSpokenLanguage('no', 'nb'), true);
    assert.equal(isSameSpokenLanguage('en-US', 'en-GB'), true);
    assert.equal(isSameSpokenLanguage('en', 'vi'), false);
  });
});

describe('selectSourceTrack', () => {
  it('prioritizes manual track matching ASR exact code over ASR track', () => {
    const tracks: CaptionTrackInfo[] = [
      { languageCode: 'vi', isAutoGenerated: false, isTranslatable: true },
      { languageCode: 'en', isAutoGenerated: true, isTranslatable: true },
      { languageCode: 'en', isAutoGenerated: false, isTranslatable: true }
    ];
    const picked = selectSourceTrack(tracks, 'en');
    assert.equal(picked?.languageCode, 'en');
    assert.equal(picked?.isAutoGenerated, false);
  });

  it('falls back to manual track matching ASR base lang, then originalAudio ASR', () => {
    const tracks: CaptionTrackInfo[] = [
      { languageCode: 'en-US', isAutoGenerated: true, isTranslatable: true },
      { languageCode: 'en-GB', isAutoGenerated: false, isTranslatable: true }
    ];
    const picked = selectSourceTrack(tracks, 'en');
    assert.equal(picked?.languageCode, 'en-GB');
    assert.equal(picked?.isAutoGenerated, false);

    const asrOnly: CaptionTrackInfo[] = [
      { languageCode: 'ja', isAutoGenerated: true, isTranslatable: true },
      { languageCode: 'en', isAutoGenerated: false, isTranslatable: true }
    ];
    const pickedOrig = selectSourceTrack(asrOnly, 'ja');
    assert.equal(pickedOrig?.languageCode, 'ja');
    assert.equal(pickedOrig?.isAutoGenerated, true);
  });
});

describe('timedtext URL helpers', () => {
  it('forces fmt=json3, checks pot, and enforces 60s expiry buffer', () => {
    const now = 1_700_000_000_000;
    const validExp = Math.floor(now / 1000) + 120;
    const expiringSoon = Math.floor(now / 1000) + 30;
    const raw = `https://www.youtube.com/api/timedtext?v=dQw4w9WgXcQ&lang=en&pot=abc123&expire=${validExp}`;
    const rewritten = buildSourceTimedtextUrl(raw);
    assert.ok(rewritten.includes('fmt=json3'));
    assert.equal(hasTimedtextPot(rewritten), true);
    assert.equal(isTimedtextUrlUsable(rewritten, 'dQw4w9WgXcQ', now), true);

    const soonUrl = `https://www.youtube.com/api/timedtext?v=dQw4w9WgXcQ&lang=en&expire=${expiringSoon}`;
    assert.equal(isTimedtextUrlUsable(soonUrl, 'dQw4w9WgXcQ', now), false);
  });
});

describe('42-language voices & rate helpers', () => {
  it('provides exact 42-language catalog aligned with tai-worker and forbids bare zh', () => {
    assert.equal(TARGET_LANGUAGES.length, 42);
    const codes = new Set(TARGET_LANGUAGES.map(l => l.code));
    for (const expected of ['te', 'mr', 'gu', 'kn', 'ml']) {
      assert.equal(codes.has(expected), true, `missing ${expected}`);
    }
    for (const removed of ['bg', 'hr', 'sl', 'sr', 'ca']) {
      assert.equal(codes.has(removed), false, `unexpected ${removed}`);
    }
    assert.equal(resolveLanguageEntry('zh'), undefined);
    assert.equal(getDefaultVoice('vi'), 'vi-VN-HoaiMyNeural');
    assert.equal(getDefaultVoice('zh-CN'), 'zh-CN-XiaoxiaoNeural');
    assert.equal(getDefaultVoice('te'), 'te-IN-ShrutiNeural');
    assert.equal(getDefaultVoice('mr'), 'mr-IN-AarohiNeural');
    assert.equal(getDefaultVoice('gu'), 'gu-IN-DhwaniNeural');
    assert.equal(getDefaultVoice('kn'), 'kn-IN-SapnaNeural');
    assert.equal(getDefaultVoice('ml'), 'ml-IN-SobhanaNeural');
    assert.equal(computeEffectiveSpeechRate(1.5, 1.0), 1.5);
    assert.equal(computeEffectiveSpeechRate(1.5, 2.0), 2.0);
    assert.equal(computeEffectiveSpeechRate(0.5, 0.5), 0.5);
    assert.equal(formatSsmlRate(1.5), '+50%');
    assert.equal(formatSsmlRate(1.0), '+0%');
    assert.equal(formatSsmlRate(0.8), '-20%');
  });
});
